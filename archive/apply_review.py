def main():
    rows = list(csv.reader(open("sheet.tsv", encoding="utf-8"), delimiter="\t"))
    head, body = rows[0], rows[1:]
    ix = {c: i for i, c in enumerate(head)}
    g, t, n = ix["gold_speaker"], ix["target"], ix["note"]
    src, uid = ix["source"], ix["uid"]
    hit = 0
    for r in body:
        key = (r[src], r[uid])
        if key in FIX:
            hit += 1
            gold, tgt, note = FIX[key]
            r[g] = gold
            if tgt == C:
                r[t] = ""
            elif tgt is not None:
                r[t] = tgt
            if note:
                r[n] = (r[n] + "; " + note) if r[n] else note
    miss = [k for k in FIX if k not in {(r[src], r[uid]) for r in body}]
    with open("sheet.tsv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(head)
        w.writerows(body)
    sys.stderr.write(f"应用修正 {hit}/{len(FIX)} 条。\n")
    if miss:
        sys.stderr.write(f"⚠ 未匹配 {len(miss)} 条(uid对不上): {miss}\n")


if __name__ == "__main__":
    main()
